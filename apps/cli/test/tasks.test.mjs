test("a prompt starts a task; tool results, meta records and injected text do not", async () => {
  const data = await load({
    s1: transcript("s1", [
      { prompt: "fix it" },
      { tools: [read("/w/a.ts")] },
      { prompt: "<system-reminder>context</system-reminder>" },
      { prompt: "Caveat: generated by local commands", meta: true },
      { tools: [edit("/w/a.ts")] },
      { out: 100 },
      { prompt: "now the other one" },
      { out: 100 },
    ]),
  });
  const tasks = buildTasks(data.events);
  assert.equal(tasks.length, 2);
  assert.equal(tasks[0].calls, 3);
  assert.equal(tasks[0].kind, "quick-edit");
  assert.equal(tasks[1].kind, "conversation");
});

test("a subagent is its own task and its own thread", async () => {
  const data = await load({
    s1: transcript("s1", [
      { prompt: "look into it" },
      { tools: [{ name: "Task", input: { prompt: "search" } }] },
      { prompt: "search", side: "ag1" },
      { tools: [read("/w/a.ts")], side: "ag1" },
      { out: 100, side: "ag1" },
      { out: 200 },
    ]),
  });
  const tasks = buildTasks(data.events);
  const sub = tasks.find((t) => t.isSubagent);
  const main = tasks.find((t) => !t.isSubagent);
  assert.equal(sub.calls, 2);
  assert.equal(sub.kind, "lookup");
  assert.equal(main.calls, 2, "the main thread's reply joins its own task, not the subagent's");
  assert.equal(main.kind, "multi-step", "delegating is more than a quick job");
});

