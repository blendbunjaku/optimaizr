test("task kinds come from shape: calls, files, failures, thinking, answer length", () => {
  const ev = (turnId, i, o = {}) => ({
    id: `${turnId}-${i}`,
    source: "claude-code",
    provider: "anthropic",
    ts: new Date(START + i * 1000).toISOString(),
    model: OPUS,
    sessionId: "s",
    project: "/w",
    turnId,
    inputTokens: 10,
    outputTokens: o.out ?? 100,
    thinkingTokens: o.think ?? 0,
    cacheReadTokens: 1000,
    cacheWrite5mTokens: 0,
    cacheWrite1hTokens: 0,
    stopReason: o.stop ?? "end_turn",
    tools: o.tools ?? [],
    cost: { total: 0.01 },
  });
  const t = (name) => ({ id: name, name, signature: `${name}:x` });
  const kindOf = (events) => buildTasks(events)[0].kind;

  assert.equal(kindOf([ev("a", 0, { tools: [t("Read")] }), ev("a", 1)]), "lookup");
  assert.equal(
    kindOf(Array.from({ length: 10 }, (_, i) => ev("b", i, { tools: [t("Read")] }))),
    "multi-step",
  );
  assert.equal(
    kindOf([
      ev("c", 0, { tools: [{ ...t("Bash"), isError: true }] }),
      ev("c", 1, { tools: [{ ...t("Bash"), isError: true }] }),
    ]),
    "debugging",
  );
  assert.equal(kindOf([ev("d", 0, { tools: [t("Read")], think: 2500 })]), "reasoning");
  assert.equal(
    kindOf([ev("e", 0, { tools: [t("Read")] }), ev("e", 1, { out: 2000 })]),
    "multi-step",
  );
  // A little thinking before a step is normal and does not make it reasoning.
  assert.equal(kindOf([ev("f", 0, { tools: [t("Read")], think: 300 })]), "lookup");
});

test("a task is done when it replied, was followed, or went quiet", () => {
  const base = {
    source: "claude-code",
    provider: "anthropic",
    model: OPUS,
    sessionId: "s",
    project: "/w",
  };
  const call = (id, turnId, min, stop) => ({
    ...base,
    id,
    turnId,
    ts: new Date(START + min * 60_000).toISOString(),
    stopReason: stop,
    inputTokens: 0,
    outputTokens: 10,
    thinkingTokens: 0,
    cacheReadTokens: 0,
    cacheWrite5mTokens: 0,
    cacheWrite1hTokens: 0,
    tools: [],
    cost: { total: 0 },
  });
  const running = buildTasks([call("1", "a", 0, "tool_use")]);
  assert.equal(running[0].done, false);
  assert.equal(buildTasks([call("1", "a", 0, "end_turn")])[0].done, true);
  const followed = buildTasks([call("1", "a", 0, "tool_use"), call("2", "b", 1, "tool_use")]);
  assert.equal(followed.find((t) => t.id === "a").done, true);
  assert.equal(
    buildTasks([call("1", "a", 0, "tool_use")], { now: START + 20 * 60_000 })[0].done,
    true,
  );
});

test("Codex prompts start tasks and a non-zero exit is a failure", () => {
  const st = createCodexState("/x/rollout.jsonl");
  const line = (type, payload) =>
    JSON.stringify({ type, timestamp: "2026-09-20T10:00:00Z", payload });
  consumeCodexLine(st, line("turn_context", { model: "gpt-5" }));
  consumeCodexLine(st, line("event_msg", { type: "user_message", message: "run tests" }));
  consumeCodexLine(
    st,
    line("response_item", {
      type: "function_call",
      call_id: "c1",
      name: "exec_command",
      arguments: '{"cmd":"npm test"}',
    }),
  );
  consumeCodexLine(
    st,
    line("response_item", {
      type: "function_call_output",
      call_id: "c1",
      output: "Process exited with code 1\nfailing",
    }),
  );
  const e = consumeCodexLine(
    st,
    line("event_msg", {
      type: "token_count",
      info: {
        total_token_usage: { total_tokens: 100 },
        last_token_usage: { input_tokens: 80, output_tokens: 20, total_tokens: 100 },
      },
    }),
  );
  assert.ok(e.turnId);
  assert.equal(e.tools[0].isError, true);
});

test("read-only commands are told apart from ones that change things", () => {
  for (const c of [
    "cd /w && git status",
    'grep -n "a\\|b" f.ts',
    "rg x > /dev/null 2>&1",
    "curl -s https://x",
  ]) {
    assert.equal(isReadOnlyCommand(c), true, c);
  }
  for (const c of [
    "npm test",
    "ls > out.txt",
    "sed -i s/a/b/ f",
    "find . -delete",
    "curl -X POST https://x",
  ]) {
    assert.equal(isReadOnlyCommand(c), false, c);
  }
});

